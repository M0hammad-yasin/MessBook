import { z } from "zod";
import { byKind, repeatingMeals, type Entity, type Meal, type Cooking } from "./domain";
import { prepareEntity, date } from "./validation";
import { isResidentOn } from "./stays";

const keySchema = z.object({
  date,
  meal: z.enum(["Breakfast", "Lunch", "Dinner", "Chai"]),
});
export const mealInputSchema = keySchema.extend({
  original: keySchema.optional(),
  /**
   * For repeating meal types (Chai), identifies the specific cooking-log id
   * being edited. Omit when creating a new session; pass the existing cooking
   * record id when editing a saved session.
   */
  slotId: z.string().max(160).optional(),
  remove: z.boolean().optional(),
  items: z
    .array(
      z.object({
        id: z.string().min(1).max(100),
        description: z.string().trim().min(1).max(300),
        amount: z.number().int().positive().max(1_000_000_000),
        paidBy: z.string().max(100),
        paidAt: z.string().optional(),
      }),
    )
    .max(100),
  memberIds: z.array(z.string()).max(1000),
  oilId: z.string().max(100),
  gasId: z.string().max(100),
  chaiId: z.string().max(100),
  // Optional manual charge for this meal, in paisa. Omitted = use the entry's average rate.
  oilRate: z.number().int().min(0).max(1_000_000_000).optional(),
  gasRate: z.number().int().min(0).max(1_000_000_000).optional(),
  chaiRate: z.number().int().min(0).max(1_000_000_000).optional(),
});
export type MealInput = z.infer<typeof mealInputSchema>;
export const isMealRecord = (
  r: Entity,
): r is Extract<Entity, { kind: "food" | "cooking" | "attendance" }> =>
  r.kind === "food" || r.kind === "cooking" || r.kind === "attendance";

/** All records belonging to a given date + meal slot. */
export function mealRecords(records: Entity[], date: string, meal: Meal) {
  return records
    .filter(isMealRecord)
    .filter((r) => r.date === date && r.meal === meal);
}

/**
 * Records belonging to a specific slot. For non-repeating meals this is the
 * same as mealRecords. For repeating meals (Chai) it is scoped to the
 * cooking-log identified by slotId so each session is independent.
 */
export function slotRecords(
  records: Entity[],
  date: string,
  meal: Meal,
  slotId?: string,
): Extract<Entity, { kind: "food" | "cooking" | "attendance" }>[] {
  const all = mealRecords(records, date, meal);
  if (!repeatingMeals.includes(meal)) return all;
  if (!slotId) return [];
  // Cooking log for this specific session
  const log = byKind(all, "cooking").find((c) => c.id === slotId);
  if (!log) return [];
  // Food and attendance share the same (date, meal) space; for a Chai slot we
  // scope food/attendance to only the records whose IDs were written alongside
  // this cooking log. We achieve this by using the slotId as a namespace prefix
  // stored in the ids generated by buildMealChanges.
  const prefix = slotId + ":";
  return [
    log,
    ...byKind(all, "food").filter((f) => f.id.startsWith(prefix)),
    ...byKind(all, "attendance").filter((a) => a.id.startsWith(prefix)),
  ];
}

/** Read legacy food, cooking and attendance as a single editable meal. */
export function readMeal(
  records: Entity[],
  date: string,
  meal: Meal,
  slotId?: string,
): MealInput {
  const rows = slotRecords(records, date, meal, slotId);
  const log = rows.find((r): r is Cooking => r.kind === "cooking");
  const items = byKind(rows, "food").flatMap((food) => {
    const credits = byKind(records, "purchase").filter(
      (p) => p.appliedTo === "Meal expense" && p.expenseId === food.id,
    );
    if (!credits.length)
      return [
        {
          id: food.id,
          description: food.description,
          amount: food.amount,
          paidBy: food.paidBy || "",
          paidAt: food.paidAt,
        },
      ];
    // Each historical contribution becomes its own ingredient row, preserving its credit date.
    const funded = credits.map((p) => ({
      id: `funded-${p.id}`,
      description: food.description,
      amount: p.amount,
      paidBy: p.memberId,
      paidAt: p.date,
    }));
    const remaining = food.amount - credits.reduce((n, p) => n + p.amount, 0);
    return [
      ...funded,
      ...(remaining > 0
        ? [
            {
              id: food.id,
              description: food.description,
              amount: remaining,
              paidBy: "",
              paidAt: undefined,
            },
          ]
        : []),
    ];
  });
  const hasRows = rows.length > 0;
  return {
    date,
    meal,
    slotId,
    ...(hasRows ? { original: { date, meal } } : {}),
    items,
    memberIds: byKind(rows, "attendance").map((r) => r.memberId),
    oilId: log?.oilId || "",
    gasId: log?.gasId || "",
    chaiId: log?.chaiId || "",
    ...(log?.oilId ? { oilRate: log.oilRate } : {}),
    ...(log?.gasId ? { gasRate: log.gasRate } : {}),
    ...(log?.chaiId ? { chaiRate: log.chaiRate ?? 0 } : {}),
  };
}

/** One atomic mutation replaces costs, attendance and buyer credits together. */
export function buildMealChanges(
  input: unknown,
  records: Entity[],
): { upsert: Entity[]; archive: string[] } {
  const value = mealInputSchema.parse(input);
  const isRepeating = repeatingMeals.includes(value.meal);

  if (
    value.original &&
    (value.original.date !== value.date || value.original.meal !== value.meal)
  )
    throw new Error(
      "A saved meal's date and type cannot be changed. Open the correct meal instead.",
    );

  // For repeating meals (Chai), slotId identifies the specific session.
  // For non-repeating meals, slotId is ignored.
  const previous = isRepeating
    ? slotRecords(records, value.date, value.meal, value.slotId)
    : mealRecords(records, value.date, value.meal);

  if (!isRepeating) {
    // Non-repeating meals (Breakfast / Lunch / Dinner): strict one-per-slot.
    if (!value.original && previous.length)
      throw new Error(
        "This meal already exists. Open the existing meal to add items.",
      );
    if (value.original && !previous.length)
      throw new Error("This meal no longer exists. Refresh before saving.");
  } else {
    // Repeating meals (Chai): creating a new session is always allowed;
    // editing requires the slotId to still exist.
    if (value.original && !previous.length)
      throw new Error(
        "This chai session no longer exists. Refresh before saving.",
      );
  }

  const oldFoodIds = byKind(previous, "food").map((r) => r.id);
  const linked = byKind(records, "purchase").filter(
    (p) => p.appliedTo === "Meal expense" && oldFoodIds.includes(p.expenseId),
  );
  if (value.remove) {
    if (!value.original)
      throw new Error(
        isRepeating
          ? "Select an existing chai session to archive"
          : "Select an existing meal to archive",
      );
    return { upsert: [], archive: [...previous, ...linked].map((r) => r.id) };
  }
  if (!value.memberIds.length)
    throw new Error("Select at least one person before saving");
  if (new Set(value.memberIds).size !== value.memberIds.length)
    throw new Error("Duplicate eaters");
  if (new Set(value.items.map((r) => r.id)).size !== value.items.length)
    throw new Error("Duplicate ingredient rows");
  const oldAttendance = byKind(previous, "attendance");
  const members = byKind(records, "member");
  for (const id of value.memberIds) {
    const member = members.find((m) => m.id === id);
    if (
      !member ||
      !isResidentOn(member, value.date) ||
      (member.status !== "Active" &&
        !oldAttendance.some((a) => a.memberId === id))
    )
      throw new Error("Only active members can be added as participants");
  }
  for (const item of value.items) {
    if (item.id.startsWith("credit:"))
      throw new Error("Ingredient ID uses a reserved payment prefix");
    if (
      records.some((r) => r.id === item.id) &&
      !previous.some((r) => r.kind === "food" && r.id === item.id)
    )
      throw new Error("Ingredient belongs to another record");
  }

  // For Chai sessions, generate a stable slot id used to namespace all records
  // belonging to this session. New sessions get a fresh uuid; edits reuse the
  // existing cooking-log id.
  const cookingId = isRepeating
    ? (value.slotId ?? crypto.randomUUID())
    : (previous.find((r) => r.kind === "cooking")?.id ?? crypto.randomUUID());
  const oldLog = previous.find((r): r is Cooking => r.kind === "cooking");
  const log = prepareEntity(
    {
      id: oldLog?.id || cookingId,
      kind: "cooking",
      date: value.date,
      meal: value.meal,
      oilId: value.oilId,
      gasId: value.gasId,
      chaiId: value.chaiId,
      oilRate: 0,
      gasRate: 0,
      chaiRate: 0,
    },
    records,
    {
      ...(value.oilId && value.oilRate !== undefined
        ? { oil: value.oilRate }
        : {}),
      ...(value.gasId && value.gasRate !== undefined
        ? { gas: value.gasRate }
        : {}),
      ...(value.chaiId && value.chaiRate !== undefined
        ? { chai: value.chaiRate }
        : {}),
    },
  );
  const oldItems = readMeal(records, value.date, value.meal, value.slotId).items;

  // For Chai sessions, food/attendance ids are prefixed with the cooking-log id
  // so they can be reliably looked up per-session in slotRecords().
  const idFor = (baseId: string) =>
    isRepeating ? `${cookingId}:${baseId}` : baseId;

  const upsert: Entity[] = [
    log,
    ...value.items.map((item) =>
      prepareEntity(
        {
          ...item,
          id: idFor(item.id),
          kind: "food",
          date: value.date,
          meal: value.meal,
          // Clients cannot move an existing credit to a different accounting date.
          paidAt: oldItems.find((r) => r.id === item.id)?.paidAt || value.date,
        },
        records,
      ),
    ),
    ...value.memberIds.map(
      (memberId): Entity => ({
        id:
          oldAttendance.find((a) => a.memberId === memberId)?.id ||
          idFor(crypto.randomUUID()),
        kind: "attendance",
        date: value.date,
        meal: value.meal,
        memberId,
      }),
    ),
  ];
  return {
    upsert,
    archive: [...previous, ...linked]
      .filter((r) => !upsert.some((u) => u.id === r.id))
      .map((r) => r.id),
  };
}
